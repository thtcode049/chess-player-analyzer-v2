@pytest.mark.parametrize("struct_key, game_data", list(BENCHMARK_28_GAMES.items()))
def test_each_structure_benchmark_game(struct_key, game_data):
    """
    Chạy từng ván cờ thực tế trong bộ benchmark qua engine analyze_structural_performance:
    1. Bắt buộc nhận diện được đúng cấu trúc mục tiêu.
    2. Nước hình thành phải nằm trong cửa sổ khai cuộc / đầu trung cuộc (nước 4 đến 16).
    3. formation_ply và formation_fen phải được lưu đầy đủ và hợp lệ.
    4. Kế hoạch chiến lược (strategic_plan) phải có đủ ideas và counter_ideas.
    """
    game = {
        "id": f"bench_{struct_key}",
        "white": game_data["white"],
        "black": game_data["black"],
        "player_color": "white",
        "result": "1-0",
        "moves": game_data["moves"],
    }

    res = analyze_structural_performance([game], min_move_window=3, max_move_window=16, min_persistence_plies=3)
    structs = res.get("structures", [])

    matched = next((s for s in structs if s["structure_key"] == game_data["expected_key"]), None)
    assert matched is not None, (
        f"FAILED to identify {struct_key} from benchmark game {game_data['white']} vs {game_data['black']}. "
        f"Detected structures: {[s['structure_key'] for s in structs]}"
    )

    # 1. Kiểm tra số ván
    assert matched["games_count"] == 1
    assert len(matched["games"]) == 1

    # 2. Kiểm tra nước hình thành (phải nằm trong khoảng 4 đến 16)
    form_move = matched["typical_formation_move"]
    assert 3 <= form_move <= 16, (
        f"Structure {struct_key} formation move {form_move} out of range [4, 16]!"
    )

    # 3. Kiểm tra chi tiết ván đấu snapshot
    snap_game = matched["games"][0]
    assert snap_game["formation_move"] == form_move
    assert snap_game["formation_ply"] >= 5, f"Formation ply too small: {snap_game['formation_ply']}"
    assert "formation_fen" in snap_game
    assert len(snap_game["formation_fen"].split()) == 6

    # 4. Kiểm tra Kế hoạch chiến lược GM
    plan = matched["strategic_plan"]
    assert plan is not None, f"Missing strategic plan for {struct_key}"
    assert len(plan["ideas"]) >= 2, f"Insufficient ideas for {struct_key}"
    assert len(plan["counter_ideas"]) >= 2, f"Insufficient counter-ideas for {struct_key}"
